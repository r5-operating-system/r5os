"""Pull the Wi-Fi parser functions out of their .c files for the host fuzzer.

The text is the source as it will be built. A distro/ copy wins over the
Haiku tree. Run from scripts/fuzz-wifi.sh.
"""
import pathlib
import sys


def pick(root, haiku, rel, haiku_rel):
    distro = root / rel
    if distro.is_file():
        return distro
    return haiku / haiku_rel


def extract(path, name):
    lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    start = None
    for i, line in enumerate(lines):
        stripped = line.strip()
        if stripped.startswith("*") or stripped.startswith("//"):
            continue
        if not line.startswith(name):
            continue
        start = i
        while start > 0:
            prev = lines[start - 1].strip()
            if "(" in prev or ";" in prev or prev.endswith("}") or prev.startswith("#"):
                break
            if (prev.startswith("/*") or prev.startswith("*")
                    or prev.endswith("*/") or prev == ""):
                break
            start -= 1
        break
    if start is None:
        raise SystemExit(f"extract: {name} not in {path}")
    depth = 0
    seen = False
    end = start
    for j in range(start, len(lines)):
        for ch in lines[j]:
            if ch == "{":
                depth += 1
                seen = True
            elif ch == "}":
                depth -= 1
        end = j
        if seen and depth == 0:
            break
    body = lines[start:end + 1]
    if body and body[0].startswith("static "):
        body[0] = body[0][len("static "):]
    elif len(body) > 1 and body[0].strip() == "static":
        body = body[1:]
    return "\n".join(body) + "\n"


def main():
    root = pathlib.Path(sys.argv[1])
    haiku = pathlib.Path(sys.argv[2])
    target = sys.argv[3]
    out = pathlib.Path(sys.argv[4])
    net = "src/libs/compat/freebsd_wlan/net80211"
    here = root / "distro/kernel" / net
    tree = haiku / net
    mtk = pick(root, haiku,
               "distro/network/wlan/mt7922wifi/dev/mtk/mtk_tx.c",
               "src/add-ons/kernel/drivers/network/wlan/mt7922wifi/dev/mtk/mtk_tx.c")

    def src(name):
        distro = here / name
        if distro.is_file():
            return distro
        return tree / name

    groups = {
        "ies": [
            (src("ieee80211_node.c"), "ieee80211_ies_init("),
            (src("ieee80211_node.c"), "ieee80211_ies_expand("),
            (src("ieee80211_input.c"), "ieee80211_parse_beacon("),
            (src("ieee80211_ht.c"), "ieee80211_parse_htcap("),
            (src("ieee80211_ht.c"), "htinfo_parse("),
            (src("ieee80211_ht.c"), "ieee80211_parse_htinfo("),
            (src("ieee80211_vht.c"), "ieee80211_parse_vhtcap("),
            (src("ieee80211_vht.c"), "ieee80211_parse_vhtopmode("),
            (src("ieee80211_sta.c"), "ieee80211_parse_wmeie("),
            (src("ieee80211_sta.c"), "ieee80211_parse_wmeparams("),
            (src("ieee80211_sta.c"), "ieee80211_parse_csaparams("),
        ],
        "rsn": [
            (src("ieee80211_hostap.c"), "wpa_cipher("),
            (src("ieee80211_hostap.c"), "rsn_cipher("),
            (src("ieee80211_hostap.c"), "wpa_keymgmt("),
            (src("ieee80211_hostap.c"), "rsn_keymgmt("),
            (src("ieee80211_hostap.c"), "ieee80211_parse_wpa("),
            (src("ieee80211_hostap.c"), "ieee80211_parse_rsn("),
        ],
        "action": [
            (src("ieee80211_input.c"), "ieee80211_parse_action("),
        ],
        "he": [
            (src("ieee80211_he.c"), "he_room("),
            (src("ieee80211_he.c"), "he_le16("),
            (src("ieee80211_he.c"), "ieee80211_parse_hecap("),
            (src("ieee80211_he.c"), "ieee80211_parse_heop("),
        ],
        "mtkrx": [
            (mtk, "mtk_rd32("),
            (mtk, "mtk_legacy_kbps("),
            (mtk, "mtk_ht_kbps("),
            (mtk, "mtk_vht_kbps("),
            (mtk, "mtk_note_txs("),
            (mtk, "mtk_receive_frame("),
        ],
    }
    if target not in groups:
        raise SystemExit(f"extract: unknown target {target}")
    parts = [
        "/* Generated by scripts/wifi-host/extract.py. Do not edit. */",
        '#include "prelude.h"',
        "",
    ]
    for path, name in groups[target]:
        parts.append(f"/* {path.name}: {name} */")
        parts.append(extract(path, name))
    out.write_text("\n".join(parts), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
