/*!	True when the control look asks for the R5 menu style: it returns more
	than Haiku's 1 for B_MENU_BACKGROUND.  margin is that inset, the space
	inside the menu window;  padding is the B_MENU_ITEM_BACKGROUND inset,
	the space around the content of an item (a row of 26 at 12 points in R5
	Modern). Haiku's looks return 1, so their menus stay as they were.
*/
/* static */
bool
MenuPrivate::R5LookStyle(BRect* padding, float* margin)
{
	if (be_control_look == NULL)
		return false;

	float left = 1, top = 1, right = 1, bottom = 1;
	be_control_look->GetBackgroundInsets(BControlLook::B_MENU_BACKGROUND, 0,
		left, top, right, bottom);
	if (!(left > 1.0f))
		return false;

	if (margin != NULL)
		*margin = floorf(left);
	if (padding != NULL) {
		float itemLeft = 1, itemTop = 1, itemRight = 1, itemBottom = 1;
		be_control_look->GetBackgroundInsets(
			BControlLook::B_MENU_ITEM_BACKGROUND, 0, itemLeft, itemTop,
			itemRight, itemBottom);
		padding->Set(floorf(itemLeft), floorf(itemTop), floorf(itemRight),
			floorf(itemBottom));
	}
	return true;
}


//! The R5 menu style for this menu: a column menu in a menu window.
bool
MenuPrivate::R5Style(BRect* padding, float* margin) const
{
	if (fMenu == NULL || fMenu->fLayout != B_ITEMS_IN_COLUMN)
		return false;
	if (dynamic_cast<BMenuWindow*>(fMenu->Window()) == NULL)
		return false;
	return R5LookStyle(padding, margin);
}


/*!	The room for the check mark in the R5 menu style: in a radio menu or a
	menu with a marked item, the content moves 16 more to the right (the
	12 px mark column after 7, and a gap of 8: mockup M6); otherwise none
	(mockup M4). BMenuItem::SetMarked() lays the menu out again when this
	changes.
*/
float
MenuPrivate::R5MarkColumn() const
{
	if (fMenu == NULL)
		return 0;
	bool marks = fMenu->IsRadioMode();
	for (int32 i = 0; !marks && i < fMenu->CountItems(); i++)
		marks = fMenu->ItemAt(i)->IsMarked();
	return marks ? roundf(16 * R5Scale()) : 0;
}


//! R5 measures are given at 12 points and follow the plain font.
/* static */
float
MenuPrivate::R5Scale()
{
	float size = be_plain_font != NULL ? be_plain_font->Size() : 12.0f;
	return std::max(size, 9.0f) / 12.0f;
}


