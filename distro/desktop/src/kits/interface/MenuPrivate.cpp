MenuPrivate::R5ShortcutFontSize() const
{
	BFont font;
	fMenu->GetFont(&font);
	return std::max(7.0f, roundf(font.Size() * 11.5f / 13.0f * 2) / 2);
}


//! The name of a modifier key from its key code, as Haiku's key caps.
static const char*
r5_key_name(uint32 key, const char* name)
{
	switch (key) {
		case 0x5c:
		case 0x60:
			return "Ctrl";
		case 0x5d:
		case 0x5f:
			return "Alt";
		case 0x66:
		case 0x67:
			return "Opt";
	}
	return name;
}


/*!	The modifier part of a shortcut as text, "Shift+Alt+", in the order of
	Haiku's key caps (Shift, Option, Control, Command). The command key is
	named by the key it is on, as Haiku's caps do (Alt by default).
*/
/* static */
void
MenuPrivate::R5ShortcutLabel(char shortcut, uint32 modifiers, char* buffer,
	size_t size)
{
	if (buffer == NULL || size == 0)
		return;

	buffer[0] = '\0';
	size_t length = 0;
	const char* names[4] = { NULL, NULL, NULL, NULL };
	if ((modifiers & B_SHIFT_KEY) != 0)
		names[0] = "Shift";
	if ((modifiers & B_OPTION_KEY) != 0)
		names[1] = r5_key_name(BMenu::sOptionKey, "Opt");
	if ((modifiers & B_CONTROL_KEY) != 0)
		names[2] = r5_key_name(BMenu::sControlKey, "Ctrl");
	if ((modifiers & B_COMMAND_KEY) != 0)
		names[3] = r5_key_name(BMenu::sCommandKey, "Alt");

	for (int32 i = 0; i < 4; i++) {
		if (names[i] == NULL || length >= size)
			continue;
		int written = snprintf(buffer + length, size - length, "%s+",
			names[i]);
		if (written < 0)
			break;
		length = std::min(size - 1, length + static_cast<size_t>(written));
	}

	// the key, as BMenuItem draws it: a symbol for the control keys
	char key[8] = { 0 };
	const char* symbol = key;
	uint8 character = static_cast<uint8>(shortcut);
	if (character == B_DELETE)
		symbol = "\xe2\x8c\xa6";
	else if (character <= B_SPACE && kUTF8ControlMap[character] != NULL)
		symbol = kUTF8ControlMap[character];
	else
		key[0] = static_cast<char>(toupper(character));
	if (length < size)
		snprintf(buffer + length, size - length, "%s", symbol);
}


/* static */
rgb_color
MenuPrivate::R5Blend(const rgb_color& from, const rgb_color& to,
	float amount)
{
	rgb_color color;
	color.red = static_cast<uint8>(roundf(from.red
		+ (to.red - from.red) * amount));
	color.green = static_cast<uint8>(roundf(from.green
		+ (to.green - from.green) * amount));
	color.blue = static_cast<uint8>(roundf(from.blue
		+ (to.blue - from.blue) * amount));
	color.alpha = 255;
	return color;
}


//! A separator: about #d3d8e0 on #f7f8fa (light), #3a404c on #262b34 (dark).
/* static */
rgb_color
MenuPrivate::R5SeparatorColor(const rgb_color& background)
{
	if (background.IsLight())
		return R5Blend(background, kR5Ink, 0.14f);
	return R5Blend(background, kR5White, 0.10f);
}
