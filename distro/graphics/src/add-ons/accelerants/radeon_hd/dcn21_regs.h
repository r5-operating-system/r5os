#define DCN21_FMT_TRUNCATE_DEPTH_MASK	0x00000030u
#define DCN21_FMT_SPATIAL_DITHER_EN		(1u << 8)
#define DCN21_FMT_SPATIAL_DITHER_MODE_MASK 0x00000600u
#define DCN21_FMT_SPATIAL_DITHER_DEPTH_SHIFT 11
#define DCN21_FMT_SPATIAL_DITHER_DEPTH_MASK 0x00001800u
#define DCN21_FMT_FRAME_RANDOM_ENABLE	(1u << 13)
#define DCN21_FMT_RGB_RANDOM_ENABLE		(1u << 14)
#define DCN21_FMT_HIGHPASS_RANDOM_ENABLE (1u << 15)
#define DCN21_FMT_TEMPORAL_DITHER_EN	(1u << 16)
#define DCN21_FMT_RAND_SEED_MASK		0xffu
// FMT_CLAMP_CNTL
#define DCN21_FMT_CLAMP_DATA_EN			(1u << 0)
#define DCN21_FMT_CLAMP_COLOR_FORMAT_MASK 0x00070000u
// FMT_422_CONTROL
#define DCN21_FMT_LEFT_EDGE_EXTRA_PIXEL_COUNT (1u << 0)

#define DCN21_DPG_CONTROL				0x1854u
#define DCN21_DPG_DIMENSIONS			0x1856u
#define DCN21_DPG_OFFSET_SEGMENT		0x185au
#define DCN21_DPG_STATUS				0x185bu
#define DCN21_DPG_EN					(1u << 0)
