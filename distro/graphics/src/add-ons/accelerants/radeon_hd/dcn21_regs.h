#define DCN21_OTG_SET_V_TOTAL_MIN_MASK_MASK 0xffff0000u
// OTG_TRIGA_CNTL
#define DCN21_OTG_TRIGA_SOURCE_SELECT_SHIFT 0
#define DCN21_OTG_TRIGA_SOURCE_PIPE_SELECT_SHIFT 5
#define DCN21_OTG_TRIGA_RISING_EDGE_DETECT_SHIFT 16
#define DCN21_OTG_TRIGA_CLEAR			(1u << 31)
// OTG_STATIC_SCREEN_CONTROL
#define DCN21_OTG_STATIC_SCREEN_EVENT_MASK 0xffffu
#define DCN21_OTG_STATIC_SCREEN_FRAME_COUNT_SHIFT 16

// ODMn_OPTC_*: stride 0x10.
#define DCN21_ODM_STRIDE				0x10u
#define DCN21_OPTC_DATA_SOURCE_SELECT	0x1acbu
#define DCN21_OPTC_DATA_FORMAT_CONTROL	0x1accu
#define DCN21_OPTC_INPUT_CLOCK_CONTROL	0x1acfu
#define DCN21_OPTC_SEG0_SRC_SEL_SHIFT	8
#define DCN21_OPTC_SEG0_SRC_SEL_MASK	0xf00u
#define DCN21_OPTC_NUM_OF_INPUT_SEGMENT	(1u << 0)
#define DCN21_OPTC_INPUT_CLK_GATE_DIS	(1u << 0)
#define DCN21_OPTC_INPUT_CLK_EN			(1u << 1)
#define DCN21_OPTC_INPUT_CLK_ON			(1u << 2)
#define DCN21_OPTC_DATA_FORMAT_MASK		0x3u

// VTGn_CONTROL: stride 1.
#define DCN21_VTG_CONTROL				0x0528u
#define DCN21_VTG_ENABLE				(1u << 31)
#define DCN21_VTG_FP2_MASK				0x7fffu
#define DCN21_VTG_VCOUNT_INIT_SHIFT		16
#define DCN21_VTG_VCOUNT_INIT_MASK		0x7fff0000u

// OPP_PIPEn, FMTn and DPGn: stride 0x5a.
#define DCN21_OPP_STRIDE				0x5au
#define DCN21_OPP_PIPE_CONTROL			0x188cu
#define DCN21_OPP_PIPE_CLOCK_EN			(1u << 0)
#define DCN21_FMT_DYNAMIC_EXP_CNTL		0x183fu
#define DCN21_FMT_CONTROL				0x1840u
#define DCN21_FMT_BIT_DEPTH_CONTROL		0x1841u
#define DCN21_FMT_DITHER_RAND_R_SEED	0x1842u
#define DCN21_FMT_DITHER_RAND_G_SEED	0x1843u
#define DCN21_FMT_DITHER_RAND_B_SEED	0x1844u
#define DCN21_FMT_CLAMP_CNTL			0x1845u
#define DCN21_FMT_422_CONTROL			0x1849u
// FMT_DYNAMIC_EXP_CNTL
#define DCN21_FMT_DYNAMIC_EXP_EN		(1u << 0)
#define DCN21_FMT_DYNAMIC_EXP_MODE		(1u << 4)
// FMT_CONTROL
#define DCN21_FMT_DITHER_FRAME_COUNTER_MAX_MASK 0x00000f00u
